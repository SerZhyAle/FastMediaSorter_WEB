"""Validate the product contract inventory and regenerate its short pointers.

Usage: py tools/contract-audit.py [--render] [--inventory FILE]
Exit codes: 0 current, 1 drift or incomplete inventory, 2 invocation/read failure.
Catalog location is resolved from CLAUDE.md. Runtime conformance is never inferred.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def outputs(data):
    groups = {}
    for row in data["contracts"]:
        groups.setdefault(row["pointer"], []).append(row)
    result = {}
    for pointer, rows in groups.items():
        lines = [f"# {' / '.join(r['id'] for r in rows)} - pointer", "",
                 "Generated by `py tools/contract-audit.py --render` from `ADOPTION.json`.",
                 "Catalog targets are not implementation claims. Resolve the catalog through CLAUDE.md.", ""]
        for row in rows:
            lines += [f"## {row['id']}", "",
                      f"- Id: `{row['id']}`.",
                      f"- Catalog target: **{row['version']}**, read {data['auditedOn']}.",
                      f"- Home: `{row['home']}`. Role: {row['role']}.",
                      f"- Scope: {row['scope']}",
                      f"- Binding references: {row['clauses']}.",
                      f"- State: **{row['state']}**. {row['finding']}",
                      f"- Implementation/evidence carriers: {', '.join(row['tickets'])}.", ""]
        result[ROOT / 'docs/contracts' / pointer] = '\n'.join(lines)
    lines = ["# Contract pointers", "",
             "Generated by `py tools/contract-audit.py --render` from `ADOPTION.json`.", "",
             "Contracts owned here: **none**. The catalog is located by CLAUDE.md; its text is not copied here.",
             "Targets below were read on " + data['auditedOn'] + "; they do not advance implementation versions.",
             "The catalog registry remains authoritative for adoption evidence and exceptions.", "",
             "| Contract | Catalog target | Pointer | State | Carriers |",
             "| --- | --- | --- | --- | --- |"]
    for row in data['contracts']:
        lines.append(f"| `{row['id']}` | {row['version']} | [{row['pointer']}]({row['pointer']}) | {row['state']} | {', '.join(row['tickets'])} |")
    lines += ["", "The accepted-proposal audit and remaining work are in",
              "[RESEARCH_contract-sync-20261019.md](../RESEARCH_contract-sync-20261019.md).",
              "The UI profile and dated migration plan are in",
              "[DESIGN_unified-ui.md](../DESIGN_unified-ui.md).", ""]
    result[ROOT / 'docs/contracts/README.md'] = '\n'.join(lines)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render', action='store_true')
    parser.add_argument('--inventory', type=Path, default=ROOT / 'docs/contracts/ADOPTION.json')
    args = parser.parse_args()
    data = json.loads(args.inventory.read_text(encoding='utf-8-sig'))
    if data['schemaVersion'] != 1:
        raise ValueError('Unsupported inventory schema')
    match = re.search(r'catalog at `([^`]+)`', (ROOT / 'CLAUDE.md').read_text(encoding='utf-8-sig'))
    if not match:
        raise ValueError('CLAUDE.md has no catalog locator')
    catalog = Path(match[1])
    failures, seen = [], set()
    registry = (catalog / '_meta/REGISTRY.md').read_text(encoding='utf-8-sig')
    catalog_rows = {}
    section = ''
    for line in registry.splitlines():
        if line.startswith('## '):
            section = line
        if section.startswith('## 1. ') and line.startswith('| `'):
            cells = [cell.strip() for cell in line.strip('|').split('|')]
            catalog_rows[cells[0].strip('`')] = cells[2]
    for row in data['contracts']:
        identifier = row['id']
        if identifier in seen:
            failures.append(f'Duplicate contract: {identifier}')
        seen.add(identifier)
        source = catalog / row['home']
        text = source.read_text(encoding='utf-8-sig')
        header = re.search(r'id: ' + re.escape(identifier) + r'\s+version: ([\d.]+)', text)
        if not header or header[1] != row['version'] or catalog_rows.get(identifier) != row['version']:
            failures.append(f'Catalog version drift: {identifier}')
        if not row['clauses'] or not row['finding'] or not row['tickets']:
            failures.append(f'Incomplete applicability/evidence: {identifier}')
        for ticket in row['tickets']:
            # TASK-FLOW rule 70 relocates a spec into PLAN/archive on an archive-status
            # move, so a carrier may live in any of the plan roots.
            if not any(list(root.glob(ticket + '_*.md')) for root in
                       (ROOT / 'PLAN', ROOT / 'PLAN' / 'archive', ROOT / 'PLAN' / 'done')):
                failures.append(f'Missing carrier: {identifier}: {ticket}')
    proposals = []
    for proposal in data['proposals']:
        path = catalog / proposal['home']
        text = path.read_text(encoding='utf-8-sig')
        current = re.search(r'^(?:\*\*Status:\*\*|Status:) (.+)', text, re.MULTILINE)
        if not current or current[1].strip() != proposal['status']:
            failures.append(f'Proposal status drift: {proposal["home"]}')
        proposals.append({'home': proposal['home'], 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    artifacts = []
    for name in data['artifacts']:
        path = catalog / name
        artifacts.append({'home': name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    # Refuse to publish stale targets, including when invoked in render mode.
    if failures:
        for failure in failures:
            print('FAIL ' + failure)
        return 1
    for path, expected in outputs(data).items():
        if args.render:
            path.write_text(expected, encoding='utf-8', newline='\n')
        elif not path.exists() or path.read_text(encoding='utf-8-sig') != expected:
            failures.append(f'Pointer drift: {path.relative_to(ROOT).as_posix()}')
    for failure in failures:
        print('FAIL ' + failure)
    report = {'date': data['auditedOn'], 'contracts': len(seen), 'proposals': proposals,
              'artifacts': artifacts, 'runtimeConformance': 'not established', 'failures': failures}
    report_dir = ROOT / 'temp/S0033'
    report_dir.mkdir(parents=True, exist_ok=True)
    (report_dir / 'contract-audit.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(f'CONTRACT-AUDIT: {"FAIL" if failures else "PASS"} - {len(seen)} targets, '
          f'{len(proposals)} proposal decisions, {len(artifacts)} artifact hashes; runtime not certified')
    return 1 if failures else 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError) as error:
        print(f'CONTRACT-AUDIT: ERROR - {error}', file=sys.stderr)
        sys.exit(2)
