export function helpText(language, entryId) {
  return (texts[language] ?? texts.en)[entryId] ?? texts.en[entryId] ?? '';
}

// Entry ids with no text, or an empty one, in any shipped language, for the gate page.
export function missingHelpTexts(entryIds, localeCodes) {
  const missing = [];
  for (const code of localeCodes) {
    for (const id of entryIds) {
      const value = texts[code]?.[id];
      if (typeof value !== 'string' || value.trim() === '') missing.push(`${code}.${id}`);
    }
    for (const id of Object.keys(texts[code] ?? {})) {
      if (!entryIds.includes(id)) missing.push(`${code}.${id} (no entry)`);
    }
  }
  return missing;
}
