export function getAdminStrings(language) {
  return dictionaries[language] ?? dictionaries.en;
}

export function missingAdminKeys() {
  const reference = Object.keys(dictionaries.en);
  const missing = [];
  for (const [language, strings] of Object.entries(dictionaries)) {
    for (const key of reference) {
      if (typeof strings[key] !== 'string' || strings[key].trim() === '') missing.push(`${language}.${key}`);
    }
    for (const key of Object.keys(strings)) {
      if (!reference.includes(key)) missing.push(`${language}.${key} (extra)`);
    }
  }
  return missing;
}
