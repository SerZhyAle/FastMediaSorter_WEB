export const localeCodes = Object.freeze(['en', 'ru', 'uk']);
export const languageNames = Object.freeze({ en: 'English', ru: 'Русский', uk: 'Українська' });

export function getStrings(language) {
  return dictionaries[localeCodes.includes(language) ? language : 'en'];
}

// Keys missing or empty in any shipped language, for the locale check of the test page.
export function missingKeys() {
  const all = new Set(localeCodes.flatMap((code) => Object.keys(dictionaries[code])));
  const missing = [];
  for (const code of localeCodes) {
    for (const key of all) {
      const value = dictionaries[code][key];
      if (typeof value !== 'string' || value.trim() === '') missing.push(`${code}.${key}`);
    }
  }
  return missing;
}
